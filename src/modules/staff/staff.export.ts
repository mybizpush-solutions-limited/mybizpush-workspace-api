import ExcelJS from "exceljs";
import { Op } from "sequelize";
import { Department, Product, Team, User } from "../../models";

// Staff export (API-CHANGES A107, ORG-06). Columns are grouped so the export
// sheet's "Include" chips map onto them. PDF staff reports come with A504.

export const EXPORT_GROUPS = ["contact", "departments", "products", "teams", "roles", "employment"] as const;
export type ExportGroup = (typeof EXPORT_GROUPS)[number];

interface Row {
  [column: string]: string;
}

export async function buildRows(groups: ExportGroup[], filter: { status?: "active" | "suspended" | "all" }): Promise<{ columns: string[]; rows: Row[] }> {
  const users = await User.findAll({
    where: filter.status && filter.status !== "all" ? { status: filter.status } : {},
    include: [
      { model: Department, as: "departments", attributes: ["name"], through: { attributes: [] } },
      { model: Product, as: "products", attributes: ["name"], through: { attributes: [] } },
      { model: Team, as: "teams", attributes: ["name"], through: { attributes: [] } },
    ],
    order: [["name", "ASC"]],
  });
  const managers = new Map(
    (await User.findAll({ where: { id: { [Op.in]: users.map((u) => u.reportsToId).filter((x): x is string => !!x) } }, attributes: ["id", "name"] })).map((m) => [m.id, m.name]),
  );
  const names = (u: User, assoc: string) => ((u.get(assoc) as { name: string }[] | undefined) ?? []).map((x) => x.name).join("; ");

  const columns = ["Name"];
  if (groups.includes("contact")) columns.push("Email", "Phone");
  if (groups.includes("employment")) columns.push("Employee ID", "Status", "Employment", "Date joined", "Reports to");
  if (groups.includes("departments")) columns.push("Departments");
  if (groups.includes("teams")) columns.push("Teams");
  if (groups.includes("products")) columns.push("Products");
  if (groups.includes("roles")) columns.push("Access level", "Job titles");

  const rows = users.map((u) => {
    const r: Row = { Name: u.name };
    if (groups.includes("contact")) Object.assign(r, { Email: u.email, Phone: u.phone ?? "" });
    if (groups.includes("employment"))
      Object.assign(r, {
        "Employee ID": u.employeeId ?? "",
        Status: u.status,
        Employment: u.employmentStatus,
        "Date joined": u.dateJoined ?? "",
        "Reports to": u.reportsToId ? (managers.get(u.reportsToId) ?? "") : "",
      });
    if (groups.includes("departments")) r.Departments = names(u, "departments");
    if (groups.includes("teams")) r.Teams = names(u, "teams");
    if (groups.includes("products")) r.Products = names(u, "products");
    if (groups.includes("roles")) Object.assign(r, { "Access level": u.accessLevel, "Job titles": u.roles.join("; ") });
    return r;
  });
  return { columns, rows };
}

const csvCell = (v: string) => (/[",\n\r]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);

export function toCsv(columns: string[], rows: Row[]): Buffer {
  const lines = [columns.map(csvCell).join(","), ...rows.map((r) => columns.map((c) => csvCell(r[c] ?? "")).join(","))];
  return Buffer.from("\uFEFF" + lines.join("\r\n"), "utf8"); // BOM so Excel reads UTF-8
}

export async function toXlsx(columns: string[], rows: Row[], meta: { generatedBy: string }): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "MyBizPush Workspace";
  const ws = wb.addWorksheet("Staff");
  ws.columns = columns.map((c) => ({ header: c, key: c, width: Math.min(40, Math.max(12, c.length + 4)) }));
  ws.getRow(1).font = { bold: true };
  ws.views = [{ state: "frozen", ySplit: 1 }];
  rows.forEach((r) => ws.addRow(r));
  const info = wb.addWorksheet("About");
  info.addRow(["Generated", new Date().toISOString()]);
  info.addRow(["Generated by", meta.generatedBy]);
  info.addRow(["Rows", rows.length]);
  return Buffer.from(await wb.xlsx.writeBuffer());
}
