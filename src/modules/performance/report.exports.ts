// Async report exports (API-CHANGES A504). The file is built in the worker, by
// calling the same report function as the requester with report.export, so what's
// in the file is limited exactly as the report is.

const KEEP_DAYS = 14;
type Req = Parameters<typeof audit>[0]["req"];

export interface ExportParams {
  id?: string;
  userId?: string;
  productId?: string;
  from?: string;
  to?: string;
  projectId?: string;
  departmentId?: string;
  teamId?: string;
  assigneeId?: string;
  sections?: string[];
}

export function serializeExport(e: ReportExport) {
  return {
    id: e.id,
    reportType: e.reportType,
    params: e.params,
    format: e.format,
    status: e.status,
    fileName: e.fileName ?? null,
    sizeBytes: e.sizeBytes ?? null,
    rows: e.rows ?? null,
    error: e.error ?? null,
    createdAt: e.createdAt.toISOString(),
    finishedAt: e.finishedAt?.toISOString() ?? null,
    expiresAt: e.expiresAt?.toISOString() ?? null,
  };
}

// Runs the report as this person, holding report.export. Throws 403 where they don't.
async function build(type: ReportType, p: ExportParams, userId: string): Promise<{ title: string; sections: Section[] }> {
  const need2 = (v: string | undefined, what: string) => {
    if (!v) throw badRequest(`Say which ${what}`);
    return v;
  };
  const q = { from: p.from, to: p.to };
  const P = "report.export";
  switch (type) {
    case "executive":
      return { title: "Executive report", sections: flatten(await reportsService.executive(userId, q, P), p.sections) };
    case "department":
      return { title: "Department report", sections: flatten(await reportsService.department(need2(p.id, "department"), userId, q, P), p.sections) };
    case "product":
      return { title: "Product report", sections: flatten(await reportsService.product(need2(p.id, "product"), userId, q, P), p.sections) };
    case "project":
      return { title: "Project report", sections: flatten(await reportsService.project(need2(p.id, "project"), userId, q, P), p.sections) };
    case "staff":
      return { title: "Staff report", sections: flatten(await reportsService.staff(need2(p.userId, "person"), userId, q, P), p.sections) };
    case "staff_product":
      return { title: "Staff in product report", sections: flatten(await reportsService.staffProduct(need2(p.userId, "person"), need2(p.productId, "product"), userId, q, P), p.sections) };
    case "task": {
      const { columns, rows } = await taskReports.exportRows(p, userId);
      return { title: "Task report", sections: [{ title: "Tasks", columns, rows }] };
    }
  }
}

function toCsvAll(sections: Section[]): Buffer {
  if (sections.length === 1) return toCsv(sections[0]!.columns, sections[0]!.rows);
  // CSV has no sheets: each section starts with its own title line.
  const parts = sections.map((s) => Buffer.concat([Buffer.from(`${s.title}\r\n`, "utf8"), toCsv(s.columns, s.rows).subarray(3), Buffer.from("\r\n\r\n", "utf8")]));
  return Buffer.concat([Buffer.from("﻿", "utf8"), ...parts]);
}

async function toXlsxAll(title: string, sections: Section[], generatedBy: string): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "MyBizPush Workspace";
  const used = new Set<string>();
  for (const s of sections) {
    // Sheet names are limited to 31 characters and must be unique.
    let name = s.title.replace(/[\\/?*[\]:]/g, " ").slice(0, 28) || "Sheet";
    for (let n = 2; used.has(name); n++) name = `${name.slice(0, 26)} ${n}`;
    used.add(name);
    const ws = wb.addWorksheet(name);
    ws.columns = s.columns.map((c) => ({ header: c, key: c, width: Math.min(44, Math.max(12, c.length + 4)) }));
    ws.getRow(1).font = { bold: true };
    ws.views = [{ state: "frozen", ySplit: 1 }];
    s.rows.forEach((r) => ws.addRow(r));
  }
  const about = wb.addWorksheet("About");
  about.addRow(["Report", title]);
  about.addRow(["Generated", new Date().toISOString()]);
  about.addRow(["Generated by", generatedBy]);
  return Buffer.from(await wb.xlsx.writeBuffer());
}

async function toPdf(title: string, sections: Section[], range: string): Promise<Buffer> {
  const { doc, chunks } = createDoc(title);
  letterhead(doc);
  doc.font("bold").fontSize(16).fillColor(INK).text(title, M, doc.y, { width: CW });
  doc.font("reg").fontSize(9).fillColor(GREY).text(range, M, doc.y, { width: CW });
  for (const s of sections) {
    h1(doc, s.title);
    const width = CW / Math.max(1, s.columns.length);
    const drawRow = (values: string[], bold: boolean) => {
      doc.font(bold ? "bold" : "reg").fontSize(8).fillColor(bold ? GREY : INK);
      const height = Math.max(...values.map((v) => doc.heightOfString(v || " ", { width: width - 6 }))) + 5;
      need(doc, height);
      const y = doc.y;
      values.forEach((v, i) => doc.text(v, M + i * width, y, { width: width - 6, lineBreak: true }));
      doc.y = y + height;
      doc.x = M;
    };
    drawRow(s.columns, true);
    for (const r of s.rows) drawRow(s.columns.map((c) => r[c] ?? ""), false);
  }
  decorate(doc, title);
  return finish(doc, chunks);
}

export const reportExports = {
  async request(input: { reportType: ReportType; params?: ExportParams; format: ExportFormat; sections?: string[] }, userId: string, req?: Req) {
    if (reachIsEmpty(await reachFor(userId, "report.export"))) throw forbidden("You don't have permission to export reports");
    const params: ExportParams = { ...(input.params ?? {}), ...(input.sections ? { sections: input.sections } : {}) };
    // Refuse now rather than fail later in the background.
    await build(input.reportType, params, userId);
    const row = await ReportExport.create({ requestedBy: userId, reportType: input.reportType, params: params as Record<string, unknown>, format: input.format });
    await audit({ req, actorId: userId, action: "report.export", target: { type: "report_export", id: row.id }, after: { reportType: input.reportType, format: input.format, params: { ...params } } });
    await enqueue("exports", "report", { exportId: row.id }, { jobId: `report-export-${row.id}` });
    return serializeExport(row);
  },

  async list(userId: string) {
    const rows = await ReportExport.findAll({ where: { requestedBy: userId }, order: [["createdAt", "DESC"]], limit: 100 });
    return rows.map(serializeExport);
  },

  async get(id: string, userId: string) {
    const row = await ReportExport.findOne({ where: { id, requestedBy: userId } });
    if (!row) throw notFound("Export not found");
    return serializeExport(row);
  },

  async download(id: string, userId: string, req?: Req) {
    const row = await ReportExport.scope(null as never).findOne({ where: { id, requestedBy: userId } });
    if (!row) throw notFound("Export not found");
    if (row.status !== "done" || !row.fileData) throw new AppError(409, "This export isn't ready", "not_ready");
    if (row.expiresAt && row.expiresAt < new Date()) throw new AppError(410, "This export has expired", "expired");
    await audit({ req, actorId: userId, action: "report.download", target: { type: "report_export", id } });
    return { fileName: row.fileName ?? "report", format: row.format, data: row.fileData };
  },

  // The worker's half.
  async run(exportId: string): Promise<void> {
    const row = await ReportExport.findByPk(exportId);
    if (!row || row.status === "done") return;
    await row.update({ status: "running" });
    try {
      const { title, sections } = await build(row.reportType, row.params as ExportParams, row.requestedBy);
      const me = await User.findByPk(row.requestedBy, { attributes: ["name"] });
      const stamp = new Date().toISOString().slice(0, 10);
      const range = row.params.from || row.params.to ? `${String(row.params.from ?? "").slice(0, 10)} to ${String(row.params.to ?? "").slice(0, 10)}` : "Last 30 days";
      const data =
        row.format === "csv" ? toCsvAll(sections)
        : row.format === "xlsx" ? await toXlsxAll(title, sections, me?.name ?? "")
        : await toPdf(title, sections, range);
      await row.update({
        status: "done",
        fileData: data,
        fileName: `${title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}-${stamp}.${row.format}`,
        sizeBytes: data.length,
        rows: rowCount(sections),
        finishedAt: new Date(),
        expiresAt: new Date(Date.now() + KEEP_DAYS * 86_400_000),
      });
    } catch (err) {
      // A refusal or bad data won't change on retry; anything else might.
      const final = err instanceof AppError;
      await row.update({ status: final ? "failed" : "queued", error: (err as Error).message.slice(0, 500), finishedAt: final ? new Date() : null });
      if (!final) throw err;
    }
    emitToUser(row.requestedBy, "export:done", { exportId: row.id, status: row.status });
  },

  async purgeExpired(): Promise<void> {
    await ReportExport.destroy({ where: { expiresAt: { [Op.lt]: new Date() } } });
  },
};
